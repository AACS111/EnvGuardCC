import { spawn } from 'node:child_process';
import { access, mkdir, writeFile, rm } from 'node:fs/promises';
import path from 'node:path';
import { setTimeout as delay } from 'node:timers/promises';
import { projectRoot as root, tauriCli, buildEnvironment } from './tauri-tools.mjs';
import { buildTimezoneService } from './build-timezone-service.mjs';
import { ensureKernel } from './net-core/vendor.mjs';

if (process.env.CHECKCC_NET_CORE !== '0' && !process.env.CHECKCC_NET_CORE_BINARY) await ensureKernel();
if (process.platform === 'darwin') await buildTimezoneService();
// Resource declarations must also resolve during development; production packaging replaces this directory.
const stage = path.join(root, 'node_modules/.checkcc-tauri-backend');
await mkdir(stage, { recursive: true });
await writeFile(path.join(stage, '.development'), 'Production resources are generated by desktop:package.\n');
await access(path.join(root, 'node_modules/next/dist/bin/next'));
const next = spawn(process.execPath, [path.join(root, 'node_modules/next/dist/bin/next'), 'dev', '--hostname', '127.0.0.1', '--port', '3030'], { cwd: root, windowsHide: true, stdio: 'inherit' });
const quitFile = path.join(root, 'node_modules/.tauri-tools', `dev-quit-${process.pid}`);
await mkdir(path.dirname(quitFile), { recursive: true });
await rm(quitFile, { force: true });
let desktop, stopping = false;
async function stop(code = 0) {
  if (stopping) return; stopping = true;
  if (desktop?.exitCode === null) {
    await writeFile(quitFile, 'quit');
    // Keep Next alive until native shutdown has restored configurations successfully.
    await new Promise(resolve => desktop.once('exit', resolve));
  }
  await rm(quitFile, { force: true });
  if (next.exitCode === null) {
    if (process.platform === 'win32') {
      await new Promise(resolve => {
        const killer = spawn('taskkill', ['/PID', String(next.pid), '/T', '/F'], { windowsHide: true, stdio: 'ignore' });
        killer.once('error', resolve); killer.once('exit', resolve);
      });
    } else next.kill('SIGTERM');
  }
  process.exitCode = code;
}
process.once('SIGINT', () => { void stop(); });
process.once('SIGTERM', () => { void stop(); });
next.once('error', error => { console.error(error.message); void stop(1); });
next.once('exit', code => { if (!stopping) void stop(code || 1); });
try {
  let ready = false;
  for (let i = 0; i < 120 && !stopping; i++) {
    try { const response = await fetch('http://127.0.0.1:3030', { signal: AbortSignal.timeout(1000) }); if (response.ok) { ready = true; break; } } catch { /* Wait for Next. */ }
    await delay(500);
  }
  if (!ready) throw new Error('Next 开发服务未就绪，请检查端口 3030。');
  desktop = spawn(process.execPath, [tauriCli(), 'dev', '--no-dev-server-wait'], { cwd: root, windowsHide: true, stdio: 'inherit', env: buildEnvironment({ CHECKCC_DESKTOP_QUIT_FILE: quitFile, CHECKCC_DESKTOP_RESOURCE_ROOT: root, CHECKCC_NODE_EXECUTABLE: process.execPath, CHECKCC_DESKTOP_DEV_URL: 'http://127.0.0.1:3030' }) });
  desktop.once('error', error => { console.error(error.message); void stop(1); });
  desktop.once('exit', code => { void stop(code || 0); });
} catch (error) { console.error('[dev:tauri] ' + error.message); await stop(1); }
